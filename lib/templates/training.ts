function material(ctx: TemplateContext): string {
  const consultation = ctx.restraintRate === null;
  const name = consultation ? "虐待防止研修資料" : "虐待防止・身体拘束等適正化研修資料";
  const body = slides(ctx)
    .map((s, i) => `## スライド${i + 1}　${s.title}\n**見出し：${s.heading}**\n\n${s.body}`)
    .join("\n\n");
  return `# ${name}（令和${ctx.reiwaYear}年度）

- 対象：${ctx.fill(ctx.facilityName, "事業所名")} 全職員（${ctx.fill(ctx.staffCount, "職員数")}名）
- 時間：60分（講義35分、事例検討15分、理解度テスト10分）
- 講師：【要記入：講師の役職・氏名】
- 実施日：【要記入】

${body}`;
}

