/** 手引きに例示がなく、事業所として扱いを決めておく場面の例 */
function unclearScenes(ctx: TemplateContext): string[] {
  if (ctx.child) return ["パニック時に一瞬抱きとめる、転倒しないよう支える", "送迎車のチャイルドロック", "鍵をかけないクールダウンスペースの使い方"];
  if (ctx.kind === "residential") return ["夜間の玄関の施錠（防犯目的との区別）", "見守りセンサー・カメラの使い方", "転落防止のベッド柵"];
  if (ctx.serviceType === "居宅介護・重度訪問介護") return ["移乗・入浴時に体を支える介助", "長時間支援でのベッド周りの柵や家具の配置"];
  if (ctx.serviceType === "短期入所") return ["夜間の廊下・出入口の施錠", "転落防止のベッド柵"];
  return ["移動中に腕をつかんで誘導する", "食事中に椅子をテーブルに寄せる"];
}

