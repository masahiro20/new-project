/** サービスごとの言葉づかい */
function words(ctx: TemplateContext) {
  const s = ctx.serviceType;
  const leader =
    s === "放課後等デイサービス" || s === "児童発達支援"
      ? "児童発達支援管理責任者"
      : s === "居宅介護・重度訪問介護"
        ? "サービス提供責任者"
        : s === "短期入所" || s === "その他の障害福祉サービス"
          ? null
          : "サービス管理責任者";
  const plan =
    s === "放課後等デイサービス"
      ? "放課後等デイサービス計画"
      : s === "児童発達支援"
        ? "児童発達支援計画"
        : s === "居宅介護・重度訪問介護"
          ? "居宅介護計画等"
          : "個別支援計画";
  return {
    /** 指針の閲覧の対象（解釈通知の言葉） */
    readers: ctx.child ? "障害児又はその家族等" : "利用者又はその家族等",
    /** 本人の呼び方 */
    person: ctx.child ? "障害児" : "利用者",
    family: ctx.child ? "保護者" : "家族",
    leader,
    plan,
    /** 3要件などを判断する職員 */
    judges: `管理者${leader ? `・${leader}` : ""}を含む複数の職員`,
  };
}

