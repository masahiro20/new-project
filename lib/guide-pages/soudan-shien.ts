身体拘束廃止未実施減算は相談支援には適用されません。指定基準でも、計画相談支援・障害児相談支援には身体拘束適正化の委員会・指針・研修の義務は置かれていません。ただし、正当な理由のない身体拘束は障害者虐待防止法上の身体的虐待にあたるため、**利用者が使っている他の事業所や家庭での身体拘束に気づく視点**は相談支援専門員にも欠かせません。

