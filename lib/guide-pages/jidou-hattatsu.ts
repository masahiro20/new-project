3. **身体拘束等の適正化のための指針**の整備
4. **身体拘束等の適正化のための研修**の年1回以上の実施

「緊急やむを得ない理由」は、**切迫性・非代替性・一時性**の3つすべてを満たし、組織として確認した手続きも記録します。未就学児の支援では、次のような場面の扱いを委員会で整理しておくと、職員の判断がそろいます（いずれも例です）。

