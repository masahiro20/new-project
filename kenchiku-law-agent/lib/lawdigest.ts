/** システムプロンプト用：分野ごとの一覧（条番号つき）。 */
export function digestToText(): string {
  const byTopic = new Map<string, DigestItem[]>();
  for (const d of DIGEST) {
    const list = byTopic.get(d.topic) ?? [];
    list.push(d);
    byTopic.set(d.topic, list);
  }
  const ref = (d: DigestItem) => (d.ref.startsWith("別表") ? `${d.law}${d.ref}` : `${d.law}${d.ref.replace(/_/g, "条の")}条`);
  return [...byTopic.entries()].map(([t, items]) => `- ${t}：${items.map((d) => `${d.point}（${ref(d)}）`).join("／")}`).join("\n");
}
