// 設計条件チェック（設計者向け）。防火指定・階数・延べ面積・構造・用途から、
// 防火・構造・省エネ・居室の規定を「該当／非該当／要確認」で照合する。
// 数値は e-Gov の現行条文（2026-10-25 確認：法2条6号・21〜26条・61条・62条、
// 令107条の2・108条・109条の2・112条・128条の4・128条の5・136条の2・136条の2の2）から。

import { lawUrl } from "./egov";
import type { PlanInput } from "./plan";

const HO = "325AC0000000201";
const REI = "325CO0000000338";
const SHOENE = "427AC0000000053";

export type DesignArea = "防火" | "構造" | "省エネ" | "居室・内装" | "敷地条件";
export const DESIGN_AREAS: DesignArea[] = ["防火", "構造", "省エネ", "居室・内装", "敷地条件"];
export type DesignVerdict = "該当" | "非該当" | "要確認";
export type DesignCite = { label: string; url: string };
export type DesignItem = {
  id: string;
  area: DesignArea;
  title: string;
  verdict: DesignVerdict;
  /** Why it applies or not, with the thresholds compared. */
  reason: string;
  /** What the designer decides / draws / specifies. */
  specs: string[];
  cites: DesignCite[];
};
export type FireClass = {
  /** e.g. 「準防火地域 3号：外壁・軒裏の防火構造＋20分の防火設備」 */
  label: string;
  /** Plain one-liner for staff. */
  plain: string;
  required: "耐火建築物等" | "準耐火建築物等" | "防火構造＋防火設備" | "防火設備" | "法22条（屋根・外壁）" | "なし" | "要確認";
};
export type DesignCheck = { fire: FireClass; basis: string; items: DesignItem[] };

const ho = (a: string, label = `建築基準法${a.replace(/_/g, "条の")}条`): DesignCite => ({ label, url: lawUrl(HO, a) });
const rei = (a: string, label = `建築基準法施行令${a.replace(/_/g, "条の")}条`): DesignCite => ({ label, url: lawUrl(REI, a) });

const isBuild = (p: PlanInput) => ["新築", "増築", "改築・大規模修繕・模様替", "未定"].includes(p.workType);
const isHouse = (p: PlanInput) => p.buildingUse === "専用住宅" || p.buildingUse === "兼用住宅（店舗・事務所併用）";

/** 法61条・令136条の2 の区分。 */
export function fireClass(p: PlanInput): FireClass {
  const n = p.floors;
  const a = p.totalFloorArea;
  const wood = p.structure === "木造" || p.structure === "未定" || p.structure === "その他・混構造";
  const known = n !== null && a !== null;
  switch (p.fireZone) {
    case "防火地域":
      if (!known) return { label: "防火地域（階数・延べ面積が未入力）", plain: "階数と延べ面積で耐火か準耐火かが決まります", required: "要確認" };
      return n >= 3 || a > 100
        ? { label: "防火地域・令136条の2 第1号：耐火建築物等", plain: "耐火建築物（RC造や木造耐火など）が必要。費用への影響が大きい", required: "耐火建築物等" }
        : { label: "防火地域・令136条の2 第2号：準耐火建築物等", plain: "準耐火建築物が必要（2階以下・延べ100㎡以下）", required: "準耐火建築物等" };
    case "準防火地域":
      if (!known) return { label: "準防火地域（階数・延べ面積が未入力）", plain: "階数と延べ面積で必要な防火仕様が決まります", required: "要確認" };
      if (n >= 4 || a > 1500) return { label: "準防火地域・令136条の2 第1号：耐火建築物等", plain: "耐火建築物が必要（地上4階以上か延べ1,500㎡超）", required: "耐火建築物等" };
      if (n === 3 || a > 500) return { label: "準防火地域・令136条の2 第2号：準耐火建築物等", plain: "準耐火建築物（または同等の延焼防止性能）が必要。地上3階建てか延べ500㎡超が対象", required: "準耐火建築物等" };
      return wood
        ? { label: "準防火地域・令136条の2 第3号：延焼のおそれのある部分の外壁・軒裏を防火構造＋開口部に20分の防火設備", plain: "隣地・道路に近い外壁・軒裏を防火仕様に、窓・玄関ドア・換気口を防火設備に", required: "防火構造＋防火設備" }
        : { label: "準防火地域・令136条の2 第4号：延焼のおそれのある部分の開口部に20分の防火設備", plain: "隣地・道路に近い窓・ドア・換気口を防火設備に", required: "防火設備" };
    case "法22条区域":
      return { label: "法22条区域：屋根の不燃化（法22条）＋木造の外壁で延焼のおそれのある部分を準防火性能（法23条）", plain: "屋根は不燃材で葺き、隣地・道路に近い外壁を準防火仕様に", required: "法22条（屋根・外壁）" };
    case "指定なし":
      return { label: "防火・準防火・法22条の指定なし（データ上）", plain: "地域による防火の義務はなし。法22条区域かは市で確認", required: "なし" };
    default:
      return { label: "防火指定が未確認", plain: "都市計画図で防火・準防火・法22条区域を確認", required: "要確認" };
  }
}

export function designCheck(p: PlanInput): DesignCheck {
  const fire = fireClass(p);
  const items: DesignItem[] = [];
  const n = p.floors;
  const a = p.totalFloorArea;
  const h = p.height;
  const wood = p.structure === "木造" || p.structure === "未定";
  const scale = `${n === null ? "階数未入力" : `${n}階建て`}・${a === null ? "延べ面積未入力" : `延べ${a}㎡`}${h === null ? "" : `・高さ${h}m`}・${p.structure}`;
  const fz = p.fireZone;
  const inFire = fz === "防火地域" || fz === "準防火地域";
  const add = (i: DesignItem) => items.push(i);

  if (!isBuild(p)) return { fire, basis: scale, items };

  // ---------------------------------------------------------------- 防火
  const enshoSpecs = [
    "配置図に延焼ライン（隣地境界線・道路中心線から1階3m／2階以上5m）を描き、ラインにかかる外壁・軒裏・開口部を拾い出す",
    "同一敷地に2棟以上（車庫・物置を含む）あれば外壁間の中心線からも測る（延べ合計500㎡以内は1棟とみなす）",
    "公園・広場・川などの空地・水面に面する部分は除外できる。外壁面と境界線の角度による緩和（国交省告示）も使える",
  ];
  if (inFire || fz === "法22条区域" || (a !== null && a > 1000)) {
    add({
      id: "ensho",
      area: "防火",
      title: "延焼のおそれのある部分の範囲",
      verdict: "該当",
      reason: `${fz}${a !== null && a > 1000 ? "・延べ1,000㎡超" : ""}のため、隣地・道路に近い部分の外壁・軒裏・開口部に防火の仕様が掛かる`,
      specs: enshoSpecs,
      cites: [ho("2", "建築基準法2条6号（延焼のおそれのある部分）")],
    });
  }

  if (fz === "防火地域" || fz === "準防火地域") {
    const c = fire.required;
    if (c === "耐火建築物等") {
      add({
        id: "fire-taika",
        area: "防火",
        title: "耐火建築物等（法61条・令136条の2 第1号）",
        verdict: "該当",
        reason: `${fz}で${scale}`,
        specs: [
          "特定主要構造部を耐火構造（令107条：柱・梁・床・耐力壁は階数に応じ1時間以上）または耐火性能検証。木造なら1時間耐火の大臣認定・告示仕様で被覆",
          "延焼のおそれのある部分の開口部に20分の防火設備（両面遮炎：令109条の2）",
          "または延焼防止時間で同等以上を確かめる方法（令136条の2 第1号ロ・国交省告示の仕様）",
          "構造種別・被覆仕様が工事費と工期を大きく左右する。計画初期に構造方針を決める",
        ],
        cites: [ho("61", "建築基準法61条"), rei("136_2", "建築基準法施行令136条の2 第1号"), rei("107", "建築基準法施行令107条（耐火性能）"), rei("109_2", "建築基準法施行令109条の2（遮炎性能）")],
      });
    } else if (c === "準耐火建築物等") {
      add({
        id: "fire-juntaika",
        area: "防火",
        title: "準耐火建築物等（法61条・令136条の2 第2号）",
        verdict: "該当",
        reason: `${fz}で${scale}`,
        specs: [
          "イ準耐火（45分）：耐力壁・柱・床・梁 45分、屋根・階段 30分の非損傷性、壁・床・軒裏 45分の遮熱性（令107条の2）。せっこうボード被覆等の告示仕様か大臣認定",
          "またはロ準耐火（令109条の3：外壁耐火型／不燃軸組型）",
          "延焼のおそれのある部分の開口部に20分の防火設備（両面遮炎：令109条の2）",
          "木造3階建て等は、延焼防止時間で同等以上を確かめる方法（令136条の2 第2号ロ・国交省告示の外壁・開口部仕様）も選べる。開口部の面積制限などの条件を設計初期に確認",
        ],
        cites: [ho("61", "建築基準法61条"), rei("136_2", "建築基準法施行令136条の2 第2号"), rei("107_2", "建築基準法施行令107条の2（準耐火性能）"), rei("109_2", "建築基準法施行令109条の2（遮炎性能）")],
      });
    } else if (c === "防火構造＋防火設備" || c === "防火設備") {
      if (c === "防火構造＋防火設備")
        add({
          id: "fire-bokakozo",
          area: "防火",
          title: "外壁・軒裏の防火構造（令136条の2 第3号イ）",
          verdict: "該当",
          reason: `準防火地域・木造・地上2階以下・延べ500㎡以下（${scale}）`,
          specs: [
            "延焼のおそれのある部分の外壁・軒裏を防火構造（30分：外壁の非損傷性・屋内側の遮熱性。令108条）。告示仕様か大臣認定（認定番号を仕様書に明記）",
            "認定品の外壁材は、認定書どおりの下地・胴縁・通気層・断熱材・目地・留付けで施工する（現場の納まりと照合）",
            "軒裏（軒天）も延焼ライン内は防火構造。軒の出がない場合も外壁で小屋裏と遮られているか確認",
            "延焼ライン外は義務なし。ただし外壁仕上げを全周で揃えるかは意匠・コストで判断",
          ],
          cites: [rei("136_2", "建築基準法施行令136条の2 第3号"), rei("108", "建築基準法施行令108条（防火性能）")],
        });
      add({
        id: "fire-opening",
        area: "防火",
        title: "開口部の防火設備（外からの火に20分）",
        verdict: "該当",
        reason: `準防火地域・地上2階以下・延べ500㎡以下（${scale}）`,
        specs: [
          "延焼ライン内の窓・玄関ドア・勝手口に、屋外側からの加熱に20分間屋内側へ火炎を出さない防火設備（防火認定のサッシ・ドア：網入り・耐熱強化ガラス等）",
          "換気口・給気口・レンジフードや浴室換気の排気口・床下換気口も開口部。延焼ライン内は防火ダンパー付きの部材にする（扱いは確認検査機関と協議）",
          "シャッター・雨戸を防火設備とする方法もある。採光・通風・意匠と合わせて開口ごとに仕様表を作る",
          "天窓・ガラスブロック・ポストや宅配ボックスの貫通も対象になり得るので拾い漏れに注意",
        ],
        cites: [rei("136_2", `建築基準法施行令136条の2 第${c === "防火設備" ? "4" : "3"}号`), ho("61", "建築基準法61条")],
      });
    }
    add({
      id: "fire-roof",
      area: "防火",
      title: "屋根（火の粉で燃えない・溶けない）",
      verdict: "該当",
      reason: `${fz}内の建築物は全て対象（法62条）`,
      specs: [
        "火の粉で発炎せず、屋内に達する溶融・亀裂を生じない屋根（令136条の2の2）。不燃材料葺き等の告示仕様か大臣認定（飛び火認定）",
        "太陽光パネル・トップライト・屋根一体型の設備は、屋根としての認定・仕様の範囲かをメーカー資料で確認",
      ],
      cites: [ho("62", "建築基準法62条"), rei("136_2_2", "建築基準法施行令136条の2の2")],
    });
    add({
      id: "fire-fence",
      area: "防火",
      title: "高さ2m超の門・塀",
      verdict: p.extras.includes("高さ2m超の門・塀") ? "該当" : "非該当",
      reason: p.extras.includes("高さ2m超の門・塀") ? `${fz}で2m超の門・塀の計画あり` : "2m超の門・塀の入力なし（計画したら延焼防止上支障のない構造が必要）",
      specs: ["防火地域内の建築物、準防火地域内の木造建築物等に附属する2m超の門・塀は延焼防止上支障のない構造（令136条の2 第5号）"],
      cites: [rei("136_2", "建築基準法施行令136条の2 第5号")],
    });
    add({
      id: "fire-63",
      area: "防火",
      title: "外壁を隣地境界線に接して建てる",
      verdict: "要確認",
      reason: "外壁が耐火構造なら、防火・準防火地域では境界線に接して設けられる（法63条。判例上、民法234条の50cmより優先）",
      specs: ["狭小地で境界いっぱいに建てる場合のみ検討。施工・維持管理の離隔は別途確保"],
      cites: [ho("63", "建築基準法63条")],
    });
  } else if (fz === "法22条区域") {
    add({
      id: "fire-22",
      area: "防火",
      title: "屋根の不燃化・外壁の準防火性能（法22条・23条）",
      verdict: "該当",
      reason: "法22条区域の建築物。外壁は木造建築物等のとき",
      specs: [
        "屋根は通常の火災の火の粉で燃え広がらない構造（不燃材料で葺く等の告示仕様か認定）",
        wood ? "延焼ライン内の外壁を準防火性能の構造（土塗壁・告示仕様・大臣認定）" : "非木造なら法23条の外壁規定は対象外",
        "開口部の防火設備は法22条区域では義務なし",
      ],
      cites: [ho("22", "建築基準法22条"), ho("23", "建築基準法23条")],
    });
  } else if (fz === "不明") {
    add({ id: "fire-unknown", area: "防火", title: "防火指定が未確認", verdict: "要確認", reason: "防火・準防火・法22条区域で外壁・開口部・屋根の仕様が変わる", specs: ["都市計画図・建築指導課で防火指定を確定してから仕様を決める"], cites: [ho("61", "建築基準法61条"), ho("22", "建築基準法22条")] });
  }

  // 大規模・面積による規定（住宅でも念のため照合）
  const over21 = (n !== null && n >= 4) || (h !== null && h > 16) || (a !== null && a > 3000);
  const under21 = n !== null && a !== null && a <= 3000 && (h !== null ? h <= 16 && n <= 3 : n <= 2);
  add({
    id: "ho21",
    area: "防火",
    title: "大規模の木造建築物（法21条）",
    verdict: !wood ? "非該当" : over21 ? "該当" : under21 ? "非該当" : "要確認",
    reason: !wood
      ? "主要構造部に可燃材料を使わない構造"
      : `地上4階以上・高さ16m超・延べ3,000㎡超のいずれかで対象（${scale}）${!over21 && !under21 && n === 3 && h === null ? "。3階建ては高さを入れると判定" : ""}`,
    specs: ["該当すれば特定主要構造部を通常火災終了時間に応じた耐火性能に（大臣が定める構造方法か認定）。3,000㎡超は壁等による区画などが必要"],
    cites: [ho("21", "建築基準法21条")],
  });
  add({
    id: "ho25",
    area: "防火",
    title: "延べ1,000㎡超の木造建築物等（法25条・26条）",
    verdict: a === null ? "要確認" : a > 1000 ? "該当" : "非該当",
    reason: a === null ? "延べ面積が未入力" : `延べ${a}㎡（基準 1,000㎡超）`,
    specs: ["該当すれば外壁・軒裏の延焼のおそれのある部分を防火構造、屋根を法22条の構造（法25条）。耐火・準耐火建築物でなければ1,000㎡以内ごとに防火壁・防火床で区画（法26条）"],
    cites: [ho("25", "建築基準法25条"), ho("26", "建築基準法26条")],
  });
  const tatebutsu = fire.required === "準耐火建築物等" || fire.required === "耐火建築物等";
  const tateNeed = tatebutsu && n !== null && n >= 3 && !(p.buildingUse === "専用住宅" && a !== null && a <= 200);
  add({
    id: "tateana",
    area: "防火",
    title: "竪穴区画（階段・吹抜け）",
    verdict: !tatebutsu ? "非該当" : n === null ? "要確認" : tateNeed ? "該当" : "非該当",
    reason: !tatebutsu
      ? "準耐火・耐火建築物とする計画ではない"
      : n !== null && n >= 3
        ? p.buildingUse === "専用住宅" && a !== null && a <= 200
          ? "階数3以下・延べ200㎡以内の一戸建て住宅は除外（令112条11項2号）"
          : "準耐火等で3階以上に居室がある。階段・吹抜けを他の部分と区画"
        : "3階以上・地階に居室がない",
    specs: [
      "階段・吹抜け・昇降路・ダクトスペースを準耐火構造の壁・床と防火設備（遮煙性能・自動閉鎖）で区画",
      "区画に接する外壁は幅90cm以上を準耐火構造（または50cm以上突き出した庇・袖壁）、その部分の開口部は防火設備（令112条16項・17項）",
      "区画を貫通する配管は隙間を不燃材料で埋め、風道には防火ダンパー（同20項・21項）",
    ],
    cites: [rei("112", "建築基準法施行令112条11項・16項")],
  });
  if (!isHouse(p) || p.buildingUse === "兼用住宅（店舗・事務所併用）")
    add({ id: "ho27", area: "防火", title: "特殊建築物の耐火・準耐火（法27条）", verdict: "要確認", reason: `${p.buildingUse}：用途部分の階・床面積で耐火・準耐火の義務が決まる`, specs: ["用途ごとの階・床面積を表にして法27条・別表第一と照合。法令の論点「特殊建築物の耐火・避難・内装制限」も参照"], cites: [ho("27", "建築基準法27条")] });

  // ---------------------------------------------------------------- 居室・内装
  if (isHouse(p)) {
    const multi = n === null ? null : n >= 2;
    add({
      id: "naiso-kaki",
      area: "居室・内装",
      title: "火気使用室の内装制限",
      verdict: multi === null ? "要確認" : multi ? "該当" : "非該当",
      reason:
        multi === null
          ? "階数が未入力"
          : multi
            ? "階数2以上の住宅：最上階以外の階にガスコンロ等の火気使用室があれば対象（最上階なら対象外）"
            : "平屋の住宅は対象外",
      specs: [
        "最上階以外のキッチン（ガスコンロ・薪ストーブ等）の壁・天井の仕上げを準不燃材料（令128条の5 第6項）。特定主要構造部が耐火構造なら対象外",
        "IHのみなら「火を使用する設備」に当たらないのが一般的な扱い（確認検査機関に確認）。コンロ周りだけ不燃化する告示の緩和もある",
        "LDK一体の場合、垂れ壁（不燃）で区画しないと内装制限の範囲がLDK全体に広がる",
      ],
      cites: [rei("128_4", "建築基準法施行令128条の4 第4項"), rei("128_5", "建築基準法施行令128条の5 第6項")],
    });
    const bigNaiso = n !== null && a !== null ? (n >= 3 && a > 500) || (n === 2 && a > 1000) || (n === 1 && a > 3000) : null;
    add({
      id: "naiso-scale",
      area: "居室・内装",
      title: "規模による内装制限（居室・廊下）",
      verdict: bigNaiso === null ? "要確認" : bigNaiso ? "該当" : "非該当",
      reason: `階数3以上で延べ500㎡超／2階で1,000㎡超／平屋で3,000㎡超が対象（${scale}）`,
      specs: ["該当すれば居室の壁（床から1.2m超）・天井を難燃材料、廊下・階段を準不燃材料"],
      cites: [rei("128_4", "建築基準法施行令128条の4 第2項・3項"), rei("128_5", "建築基準法施行令128条の5 第4項")],
    });
  }
  add({
    id: "sickhouse",
    area: "居室・内装",
    title: "採光・換気・シックハウス",
    verdict: "該当",
    reason: "居室のある建築物は全て対象",
    specs: [
      "居室ごとに採光（住宅は床面積の1/7以上、採光補正係数で隣地・庇の影響を算定）と換気（1/20以上か換気設備）を確認",
      "24時間換気（居室0.5回/h以上）とF☆☆☆☆建材の使用を仕様書に明記",
    ],
    cites: [ho("28", "建築基準法28条"), ho("28_2", "建築基準法28条の2")],
  });

  // ---------------------------------------------------------------- 構造
  if (wood) {
    const keisan = n !== null && a !== null ? n >= 3 || a > 300 : null;
    add({
      id: "kozo-keisan",
      area: "構造",
      title: "構造計算（木造）",
      verdict: keisan === null ? "要確認" : keisan ? "該当" : "非該当",
      reason: `木造は地上3階以上か延べ300㎡超で許容応力度計算等、4階以上か高さ16m超はさらに高度な計算（${scale}）`,
      specs: keisan ? ["許容応力度計算（ルート1以上）の構造計算書。構造設計者の手配と工程を早めに"] : ["構造計算は不要でも、壁量・壁の配置（四分割法等）・柱の小径・接合部・基礎の仕様規定に適合させる"],
      cites: [ho("20", "建築基準法20条")],
    });
  }
  const shin2 = n !== null && a !== null ? n >= 2 || a > 200 : null;
  add({
    id: "shin2",
    area: "構造",
    title: "確認申請の区分（新2号・新3号）",
    verdict: shin2 === null ? "要確認" : "該当",
    reason: shin2 === null ? "階数・延べ面積が未入力" : shin2 ? "階数2以上か延べ200㎡超：新2号建築物（構造・省エネの図書も審査）" : "平屋かつ延べ200㎡以下：新3号建築物（審査は一部省略、基準への適合は必要）",
    specs: [
      "新2号なら壁量計算書・柱の小径・基礎・接合部の図書を申請図に入れる",
      "壁量は2025年4月改正後の基準（屋根・外壁の重さや太陽光パネルの荷重に応じて必要壁量を算定）。旧早見表は使わない",
    ],
    cites: [ho("6", "建築基準法6条"), rei("46", "建築基準法施行令46条（構造耐力上必要な軸組等）"), rei("43", "建築基準法施行令43条（柱の小径）")],
  });

  // ---------------------------------------------------------------- 省エネ
  add({
    id: "shoene",
    area: "省エネ",
    title: "省エネ基準への適合",
    verdict: "該当",
    reason: "2025年4月以降の新築・増改築は全て適合義務",
    specs: [
      "外皮（UA値・ηAC値）と一次エネルギー消費量の計算、または仕様基準で確認",
      shin2 === false ? "新3号は省エネ適判の対象外（基準への適合は必要）" : "仕様基準でなければ確認申請前に省エネ適合性判定",
      inFire ? "防火サッシ・防火構造の外壁は断熱仕様・U値の選択肢が限られる。防火認定と断熱性能を同時に満たす製品を選ぶ" : "サッシ・断熱材の仕様を外皮計算と合わせる",
    ],
    cites: [{ label: "建築物省エネ法 10条・11条", url: lawUrl(SHOENE, "10") }],
  });

  // ---------------------------------------------------------------- 敷地条件
  const hz = p.hazards;
  if (hz.includes("浸水想定区域"))
    add({ id: "flood", area: "敷地条件", title: "浸水想定への備え", verdict: "該当", reason: "浸水想定区域内（想定深さはハザードマップで確認）", specs: ["1階床高さ・基礎高さを想定浸水深と比べて検討", "給湯器・分電盤・室外機など設備を高い位置に", "水害の保険・お客様への説明"], cites: [{ label: "国土交通省 ハザードマップポータル", url: "https://disaportal.gsi.go.jp/" }] });
  if (hz.includes("土砂災害特別警戒区域（レッド）"))
    add({ id: "red", area: "敷地条件", title: "土砂災害特別警戒区域の構造規制", verdict: "該当", reason: "レッドゾーン内の居室のある建築物は、想定される衝撃に耐える構造（令80条の3）", specs: ["崖側の外壁をRC造の待受け壁等にする構造計算", "開発・建築の許可要否を県に確認"], cites: [rei("80_3", "建築基準法施行令80条の3")] });
  if (p.extras.includes("高さ2m超の擁壁・崖に近接"))
    add({ id: "gake", area: "敷地条件", title: "崖・擁壁の近接", verdict: "要確認", reason: "崖条例（県・市の条例）で崖からの離隔か擁壁・基礎の措置が必要な場合がある", specs: ["崖高さの2倍などの離隔、または深基礎・擁壁の安全確認（条例の数値を確認）"], cites: [ho("19", "建築基準法19条（敷地の衛生及び安全）")] });

  return { fire, basis: scale, items };
}

export function designCheckToText(d: DesignCheck): string {
  const lines = [`- 防火の区分：${d.fire.label}（${d.basis}）`];
  for (const area of DESIGN_AREAS) {
    const its = d.items.filter((i) => i.area === area);
    if (!its.length) continue;
    lines.push(`## ${area}`);
    for (const i of its) lines.push(`- ［${i.verdict}］${i.title}：${i.reason}${i.verdict === "非該当" ? "" : `。設計で決めること：${i.specs.join("／")}`}（${i.cites.map((c) => c.label).join("・")}）`);
  }
  return lines.join("\n");
}
