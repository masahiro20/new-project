export const AXIS_ORDER: Axis[] = ["dom", "amae", "mood", "demand"];

const KEY: Record<string, Axis> = { d: "dom", a: "amae", m: "mood", r: "demand" };

/** "d2a1m-1" のような短い記法を {dom:2, amae:1, mood:-1} に変換する */
export function delta(spec: string): Delta {
  const out: Delta = {};
  for (const [, k, n] of spec.matchAll(/([damr])(-?\d)/g)) out[KEY[k]] = Number(n);
  return out;
}

export const ch = (label: string, spec: string, obs: string): Choice => ({ label, d: delta(spec), obs });

