/** cat.ts の並び（柄→猫種）にそろえる */
export const BREEDS: Breed[] = BREED_IDS.map((id) => LIST.find((b) => b.id === id)!).filter(Boolean);

export const BREED_BY_ID = new Map(BREEDS.map((b) => [b.id, b]));

export function getBreed(id: string | undefined): Breed {
  return BREED_BY_ID.get(id as BreedId) ?? BREEDS[0];
}

